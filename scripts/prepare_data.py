"""Validate the raw roll logs and create the cleaned analysis dataset.

Usage (from the repository root):

    python scripts/prepare_data.py

Reads data/raw/roll_log_A.csv (and roll_log_B.csv if the fallback machine was
used), applies the validation rules in docs/preprocessing_plan.md, and writes:

    data/cleaned/analysis_data.csv   cleaned dataset (docs/data_dictionary.md)
    results/validation_summary.md    counts to commit alongside the data

Nothing is written if validation fails. The raw files are never modified.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import craps_core as core

REPO_ROOT = Path(__file__).resolve().parent.parent


def write_summary(path: Path, summary: dict, raw_dir: Path, mismatches_accepted: bool) -> None:
    lines = [
        "# Validation Summary",
        "",
        "Generated by `scripts/prepare_data.py` from `data/raw`.",
        "",
        "## Sample",
        "",
        f"- Counted rolls: **{summary['counted_rolls']}** of {summary['target_rolls']} "
        "(excludes each machine's row 0 and `GAP` rows).",
        f"- Ended early: {'yes, shortfall of ' + str(summary['shortfall']) if summary['ended_early'] else 'no'}.",
        f"- Rows logged beyond the target and excluded: {summary['rows_beyond_target_removed']}.",
        f"- Fallback machine B used: {'yes' if summary['machine_switch'] else 'no'}.",
        "",
        "## By machine",
        "",
    ]
    fields = [
        ("rows", "Rows in cleaned data"),
        ("counted_rolls", "Counted rolls"),
        ("gaps", "`GAP` rows"),
        ("recovered_rolls_excluding_row_0", "Recovered from history (`R`, excluding row 0)"),
        ("corrected_rolls", "Corrected outcomes (`C`; source in notes)"),
        ("rows_noting_a_break", "Rows whose notes mention a break"),
        ("analysis_blocks", "Analysis blocks"),
        ("valid_pairs", "Valid adjacent pairs (H1/H2)"),
        ("h3_eligible_rolls", "H3-eligible rolls"),
        ("counted_rolls_with_unknown_phase", "Counted rolls with unknown phase (excluded from H3)"),
        ("phase_mismatches", "Phase mismatches"),
        ("blank_rows_dropped", "Fully blank rows dropped"),
    ]
    machines = sorted(summary["machines"])
    lines.append("| | " + " | ".join(machines) + " |")
    lines.append("|---|" + "---|" * len(machines))
    for key, label in fields:
        values = [str(summary["machines"][m][key]) for m in machines]
        lines.append(f"| {label} | " + " | ".join(values) + " |")
    lines.append("")
    if summary["phase_mismatch_rows"]:
        lines += ["## Phase mismatches", ""]
        for r in summary["phase_mismatch_rows"]:
            lines.append(f"- Machine {r['machine_id']}, roll {r['roll_number']} (sheet row {r['sheet_row']})")
        if mismatches_accepted:
            lines += ["", "These were accepted with `--allow-phase-mismatch`; the recorded phase was used. "
                      "Each must be explained in `docs/deviations.md`."]
        lines.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--raw-dir", type=Path, default=REPO_ROOT / "data" / "raw")
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "data" / "cleaned" / "analysis_data.csv")
    parser.add_argument("--summary", type=Path, default=REPO_ROOT / "results" / "validation_summary.md")
    parser.add_argument("--target", type=int, default=core.TARGET_ROLLS)
    parser.add_argument("--allow-phase-mismatch", action="store_true",
                        help="Write the cleaned file even if recorded and reconstructed phases disagree. "
                             "Only after each mismatch is explained in docs/deviations.md.")
    parser.add_argument("--force", action="store_true",
                        help="Overwrite an existing cleaned file. The plan is to create it once.")
    args = parser.parse_args(argv)

    prepared = core.prepare(args.raw_dir, target=args.target)
    if prepared.issues:
        print(f"Validation failed with {len(prepared.issues)} problem(s). Nothing was written.\n")
        for issue in prepared.issues:
            print(f"  {issue}")
        return 1

    summary = core.summarize(prepared, target=args.target)
    if summary["phase_mismatch_rows"] and not args.allow_phase_mismatch:
        print("Recorded phases disagree with the reconstructed phase at:\n")
        for r in summary["phase_mismatch_rows"]:
            print(f"  machine {r['machine_id']}, roll {r['roll_number']} (sheet row {r['sheet_row']})")
        print("\nResolve and document each in docs/deviations.md, then rerun with "
              "--allow-phase-mismatch. Nothing was written.")
        return 1

    if args.out.exists() and not args.force:
        print(f"{args.out} already exists. The cleaned file is created once; use --force to overwrite.")
        return 1

    args.out.parent.mkdir(parents=True, exist_ok=True)
    prepared.cleaned.to_csv(args.out, index=False)
    write_summary(args.summary, summary, args.raw_dir, args.allow_phase_mismatch)

    print(f"Wrote {args.out} ({len(prepared.cleaned)} rows, {summary['counted_rolls']} counted rolls).")
    print(f"Wrote {args.summary}.")
    if summary["ended_early"]:
        print(f"Note: the session ended {summary['shortfall']} rolls short of {args.target}.")
    if summary["rows_beyond_target_removed"]:
        print(f"Note: {summary['rows_beyond_target_removed']} rows after roll {args.target} were excluded.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
